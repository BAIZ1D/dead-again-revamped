import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const gameDir = path.join(rootDir, 'main');
const srcDir = path.join(gameDir, 'src');
const distDir = path.join(gameDir, 'dist');
const distJsDir = path.join(distDir, 'js');

function buildGame() {
  const startTime = Date.now();

  // Ensure output directories exist
  fs.mkdirSync(distJsDir, { recursive: true });

  // 1. Process Tiled maps into src/js/start_GEN.js
  const maps = ['0', '1', '2'];
  let mapStr = '// THIS FILE IS GENERATED BY THE BUILD SCRIPT\n';
  mapStr += 'let mapData = [];\n';

  for (let i = 0; i < maps.length; i++) {
    const mapPath = path.join(srcDir, 'maps', `${maps[i]}.json`);
    const mapJson = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
    const rawData = mapJson.layers[0].data
      .toString()
      .replaceAll(',0,', ',,')
      .replaceAll(',0,', ',,');
    mapStr += `mapData[${i}] = { w: ${mapJson.width}, h: ${mapJson.height}, data: [${rawData}] }; \n`;
  }
  mapStr += '\ninit();\n';

  const startGenPath = path.join(srcDir, 'js', 'start_GEN.js');
  fs.writeFileSync(startGenPath, mapStr, 'utf8');

  // 2. Ensure dist/t.png exists by copying src/gfx/tiles.png
  const srcTiles = path.join(srcDir, 'gfx', 'tiles.png');
  const distTiles = path.join(distDir, 't.png');
  if (fs.existsSync(srcTiles)) {
    let shouldCopy = !fs.existsSync(distTiles);
    if (!shouldCopy) {
      const srcStat = fs.statSync(srcTiles);
      const distStat = fs.statSync(distTiles);
      if (srcStat.mtimeMs > distStat.mtimeMs) {
        shouldCopy = true;
      }
    }
    if (shouldCopy) {
      fs.copyFileSync(srcTiles, distTiles);
    }
  }

  // 3. Copy src/html/index_dev.html to dist/index.html
  const srcHtml = path.join(srcDir, 'html', 'index_dev.html');
  const distHtml = path.join(distDir, 'index.html');
  fs.copyFileSync(srcHtml, distHtml);

  // 4. Concatenate JS files in exact dependency order
  const jsDir = path.join(srcDir, 'js');
  const libDir = path.join(jsDir, 'lib');
  const orderedFiles = [];

  // 4a. src/js/lib/*.js (if any)
  if (fs.existsSync(libDir)) {
    const libFiles = fs
      .readdirSync(libDir)
      .filter((f) => f.endsWith('.js'))
      .sort((a, b) => a.localeCompare(b, 'en'));
    for (const f of libFiles) {
      orderedFiles.push(path.join(libDir, f));
    }
  }

  // 4b. main.js and DEFS.js first
  orderedFiles.push(path.join(jsDir, 'main.js'));
  orderedFiles.push(path.join(jsDir, 'DEFS.js'));

  // 4c. Base classes and APG network adapter before subclasses, then remaining src/js/*.js
  const priorityFiles = ['sounds.js', 'music.js', 'apgNetwork.js', 'apgManager.js', 'mob_base.js', 'mob_enemy.js', 'gun.js'];
  for (const pf of priorityFiles) {
    const fullPath = path.join(jsDir, pf);
    if (fs.existsSync(fullPath)) {
      orderedFiles.push(fullPath);
    }
  }

  const excluded = new Set(['main.js', 'DEFS.js', 'start_GEN.js', ...priorityFiles]);
  const otherJsFiles = fs
    .readdirSync(jsDir)
    .filter((f) => f.endsWith('.js') && !excluded.has(f))
    .sort((a, b) => a.localeCompare(b, 'en'));

  for (const f of otherJsFiles) {
    orderedFiles.push(path.join(jsDir, f));
  }

  // 4d. Finally start_GEN.js
  orderedFiles.push(startGenPath);

  const combinedSource = orderedFiles
    .map((filePath) => fs.readFileSync(filePath, 'utf8'))
    .join('\n');

  const outJsPath = path.join(distJsDir, 'index.js');
  fs.writeFileSync(outJsPath, combinedSource, 'utf8');

  const elapsed = Date.now() - startTime;
  console.log(`[Build] Compiled ${orderedFiles.length} files into dist/js/index.js in ${elapsed}ms`);
}

buildGame();
